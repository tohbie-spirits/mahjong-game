/**
 * build-docs.mjs — Task 120: writes docs/rules-reference.md from the three
 * rules-reference modules (src/rules/<ruleset>/<Ruleset>Reference.js) — the
 * same data the in-game Rules screen shows, which those modules read from
 * the engines' own scoring tables and defaults. The document therefore can't
 * drift from the rules actually played: tests/core/docs.test.mjs fails when
 * the checked-in file differs from what this script generates.
 *
 *   node tools/build-docs.mjs           (rewrite docs/rules-reference.md)
 *   node tools/build-docs.mjs --check   (exit 1 if it is out of date)
 *
 * `renderRulesReference()` is exported for the test.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getHongKongReference } from '../src/rules/hongkong/HongKongReference.js';
import { getRiichiReference } from '../src/rules/riichi/RiichiReference.js';
import { getChineseOfficialReference } from '../src/rules/chineseOfficial/ChineseOfficialReference.js';
import { Tile } from '../src/core/Tile.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const RULES_REFERENCE_PATH = resolve(ROOT, 'docs/rules-reference.md');

const tileName = (id) => { try { return Tile.fromId(id).label; } catch { return id; } };
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');
const anchor = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function renderBlock(b) {
  if (b.type === 'p') return `${b.text}\n`;
  if (b.type === 'list') return `${b.items.map((i) => `- ${i}`).join('\n')}\n`;
  if (b.type === 'tiles') return `> ${b.caption ? `${b.caption}: ` : ''}${b.tiles.map(tileName).join(' · ')}\n`;
  return '';
}

function renderOne(ref) {
  const out = [];
  out.push(`## ${ref.title} (${ref.native})`, '', ref.summary, '');
  out.push('| | |', '|---|---|', ...ref.facts.map((f) => `| **${esc(f.label)}** | ${esc(f.value)} |`), '');
  for (const s of ref.sections) {
    out.push(`### ${s.title}`, '');
    for (const b of s.blocks) out.push(renderBlock(b));
  }
  out.push(`### ${ref.scoring.title}`, '');
  if (ref.scoring.intro) out.push(ref.scoring.intro, '');
  for (const g of ref.scoring.groups) {
    out.push(`#### ${g.title}`, '', `| Pattern | Also called | Value | Note |`, '|---|---|---|---|');
    for (const r of g.rows) out.push(`| ${esc(r.name)} | ${esc(r.native ?? '')} | ${esc(r.value)} | ${esc(r.note ?? '')} |`);
    out.push('');
  }
  out.push('### Glossary', '', '| Term | Native | Meaning |', '|---|---|---|', ...ref.glossary.map((g) => `| ${esc(g.term)} | ${esc(g.native ?? '')} | ${esc(g.meaning)} |`), '');
  return out.join('\n');
}

export function renderRulesReference() {
  const refs = [getHongKongReference(), getRiichiReference(), getChineseOfficialReference()];
  const head = [
    '<!-- GENERATED by tools/build-docs.mjs from src/rules/*/…Reference.js — do not edit by hand. -->',
    '# Rules reference',
    '',
    'The three rulesets **as this game plays them** — the same text as the in-game Rules screen (main menu → Rules, or Pause → Rules).',
    'Every scoring value below is read from the engine\'s own tables, so this page always matches the code; regenerate it with `node tools/build-docs.mjs` after changing a ruleset (`tests/core/docs.test.mjs` fails if you forget).',
    '',
    ...refs.map((r) => `- [${r.title}](#${anchor(`${r.title} ${r.native}`)})`),
    '',
  ];
  return `${[...head, ...refs.map(renderOne)].join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const text = renderRulesReference();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(RULES_REFERENCE_PATH, 'utf8'); } catch { /* missing */ }
    if (current !== text) { console.error('docs/rules-reference.md is out of date — run: node tools/build-docs.mjs'); process.exit(1); }
    console.log('docs/rules-reference.md is up to date.');
  } else {
    mkdirSync(dirname(RULES_REFERENCE_PATH), { recursive: true });
    writeFileSync(RULES_REFERENCE_PATH, text);
    console.log(`wrote ${RULES_REFERENCE_PATH} (${text.split('\n').length} lines)`);
  }
}
